/**
 * Works out how much each waypoint's corner may be rounded when drawn.
 *
 * Rounding bends the line into the inside of a turn. In mid-ocean there is room
 * for a wide, sweeping arc; off a headland or between islands there is none.
 * Rather than pick one timid radius that is invisible at world zoom, or one
 * generous radius that beaches the line, this measures the room available at
 * every corner the graph can produce and writes the answer into
 * `src/data/corner-radii.ts`.
 *
 * Run with `npm run generate:radii` after moving any waypoint.
 */
import { writeFileSync } from 'node:fs'
import { LINKS, WAYPOINTS } from '../src/data/network.ts'
import { PORTS, portNodeId } from '../src/data/ports.ts'
import { isRoundableCorner } from '../src/engine/graph.ts'
import { DEFAULT_CORNER, cornerArc, type LatLon } from '../src/engine/geo.ts'
import { createCoastProximity, isLand } from './land.ts'

/** Arcs must stay clear of the shore, not merely off it. */
const nearCoast = createCoastProximity(0.2, 1)

/** Radii to try, largest first; the first one that clears land wins. */
const CANDIDATES_NM = [600, 450, 340, 250, 180, 130, 90, 60, 40, 25]

/**
 * The arc is kept well inside the radius that merely grazes land. A 50m
 * coastline is a coarse instrument, and this is only cosmetic — there is no
 * reason to spend the margin.
 */
const SAFETY = 0.55

/** Denser than the render, so a thin spit between samples cannot be missed. */
const CHECK_SAMPLES = 48

const nodes = new Map<string, LatLon>()
for (const w of WAYPOINTS) nodes.set(w.id, { lat: w.lat, lon: w.lon })
for (const p of PORTS) nodes.set(portNodeId(p.id), { lat: p.lat, lon: p.lon })

const adjacency = new Map<string, Set<string>>()
const link = (a: string, b: string) => {
  if (!adjacency.has(a)) adjacency.set(a, new Set())
  if (!adjacency.has(b)) adjacency.set(b, new Set())
  adjacency.get(a)!.add(b)
  adjacency.get(b)!.add(a)
}
for (const [a, b] of LINKS) link(a, b)
for (const p of PORTS) for (const anchor of p.anchors) link(portNodeId(p.id), anchor)

const clearAt = (a: LatLon, v: LatLon, c: LatLon, radiusNm: number) => {
  const arc = cornerArc(a, v, c, {
    ...DEFAULT_CORNER,
    maxRadiusNm: radiusNm,
    minRadiusNm: 0,
    samples: CHECK_SAMPLES,
  })
  return arc === null || !arc.some((p) => isLand(p) || nearCoast(p))
}

const radii: Record<string, number> = {}
let corners = 0
let sharp = 0

for (const [vertex, neighbourSet] of adjacency) {
  const neighbours = [...neighbourSet]
  let vertexCap = Infinity

  for (let i = 0; i < neighbours.length; i++) {
    for (let j = i + 1; j < neighbours.length; j++) {
      const [previous, next] = [neighbours[i], neighbours[j]]
      if (!isRoundableCorner(previous, vertex, next)) continue
      corners++

      const a = nodes.get(previous)!
      const v = nodes.get(vertex)!
      const c = nodes.get(next)!

      const largest = CANDIDATES_NM.find((r) => clearAt(a, v, c, r)) ?? 0
      vertexCap = Math.min(vertexCap, largest * SAFETY)
    }
  }

  if (vertexCap === Infinity) continue
  const rounded = Math.round(vertexCap)
  if (rounded < DEFAULT_CORNER.minRadiusNm) sharp++
  radii[vertex] = rounded
}

const entries = Object.entries(radii).sort(([a], [b]) => a.localeCompare(b))
const body = entries.map(([id, r]) => `  '${id}': ${r},`).join('\n')

writeFileSync(
  new URL('../src/data/corner-radii.ts', import.meta.url),
  `/**
 * Largest corner-rounding radius, in nautical miles, that keeps the drawn line
 * off the coastline at each waypoint.
 *
 * Generated by \`npm run generate:radii\` — do not edit by hand. A waypoint
 * missing from this map is never rounded, so forgetting to regenerate loses
 * smoothing rather than putting a route ashore.
 */
export const CORNER_RADII: Record<string, number> = {
${body}
}
`,
  'utf8',
)

const values = entries.map(([, r]) => r)
const median = values.slice().sort((a, b) => a - b)[Math.floor(values.length / 2)]
console.log(
  `${corners} corners measured across ${entries.length} waypoints.\n` +
    `radius: median ${median} nm, max ${Math.max(...values)} nm, ` +
    `${sharp} waypoint(s) left sharp.`,
)
